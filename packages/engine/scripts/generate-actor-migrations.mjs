#!/usr/bin/env node
/**
 * Bundle the engine's SQL migrations for the durable-actor adapter.
 *
 * Actor code can't read the filesystem, and an actor database executes one
 * statement per call, so this writes `src/adapters/actor/migrations.generated.ts`
 * with every migration already split into statements, plus the supersession
 * manifest. Run `npm run generate:actor-migrations` after adding a migration;
 * a unit test fails when the module is stale.
 *
 * Usage: node scripts/generate-actor-migrations.mjs [--check]
 */
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { splitSqlStatements } from './split-sql-statements.mjs';

const engineRoot = join(dirname(fileURLToPath(import.meta.url)), '..');
const migrationsDir = join(engineRoot, 'src/db/migrations');
const outFile = join(engineRoot, 'src/adapters/actor/migrations.generated.ts');

export function renderActorMigrations() {
  const files = readdirSync(migrationsDir).filter((file) => file.endsWith('.sql')).sort();
  const migrations = files.map((file) => [file, splitSqlStatements(readFileSync(join(migrationsDir, file), 'utf8'))]);
  const supersessions = JSON.parse(readFileSync(join(migrationsDir, 'supersessions.json'), 'utf8'));
  return [
    '// Generated by scripts/generate-actor-migrations.mjs from src/db/migrations. Do not edit.',
    '',
    '/** Each engine migration file, split into single statements. */',
    `export const ACTOR_MIGRATIONS: readonly (readonly [string, readonly string[]])[] = ${JSON.stringify(migrations, null, 2)};`,
    '',
    '/** `src/db/migrations/supersessions.json`. */',
    `export const ACTOR_MIGRATION_SUPERSESSIONS: unknown = ${JSON.stringify(supersessions, null, 2)};`,
    '',
  ].join('\n');
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const rendered = renderActorMigrations();
  if (process.argv.includes('--check')) {
    if (readFileSync(outFile, 'utf8') !== rendered) {
      console.error(`${outFile} is stale; run node scripts/generate-actor-migrations.mjs`);
      process.exit(1);
    }
  } else {
    writeFileSync(outFile, rendered);
  }
}
